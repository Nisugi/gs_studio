//! With the `bundled-art` feature, packs an art pool and the rig data into
//! the binary: `$OUT_DIR/bundle.bin` (every file, end to end) and
//! `$OUT_DIR/bundle_index.rs` (where each one starts). `src/bundle.rs`
//! includes both and seeds gs-studio's own pool / data root from them.
//!
//! Sources, read at BUILD time:
//!   GS_STUDIO_EMBED_POOL  a pool (VellumFE-shaped): global/images (minus
//!                         the injury dolls, ~720 MB of overlays, and the
//!                         creature art), global/scenes and global/skins
//!                         are packed. Required with the feature.
//!   GS_STUDIO_EMBED_DATA  a data root: outlines.json, rigs/, poses/, props/,
//!                         outfits/ and textures/ (only the files the texture
//!                         generator reads and writes -- not the reference
//!                         art dropped beside them). Default: the
//!                         workspace's data/.
//! Backups (`*.bak` files and directories) are skipped.
//!
//! Without the feature both outputs are empty, so a normal build stays small
//! and fast to link.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// Pool subtrees packed, relative to the pool root.
const POOL_PARTS: &[&str] = &["global/images", "global/scenes", "global/skins"];
/// Left out of those, relative to the pool root: the injury dolls, and the
/// creature art (the stage draws every creature as its puppet instead).
const POOL_EXCLUDED: &[&str] = &["global/images/dolls", "global/images/creatures"];
/// Data-root entries packed, relative to the data root.
const DATA_PARTS: &[&str] = &["outlines.json", "rigs", "poses", "props", "outfits", "textures"];
/// Under `textures/`, the only files packed: the texture generator's own
/// (`studio/src/editor/texture.rs`), by name or by ending.
const TEXTURE_NAMES: &[&str] = &["front.png", "side.png", "back.png", "sheet.png", "pattern.png", "patches.txt", "marks.json"];
const TEXTURE_ENDINGS: &[&str] = &["_paint.png", "_depth.png", "_render.png", "_unpainted.png"];

fn main() {
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR"));
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=GS_STUDIO_EMBED_POOL");
    println!("cargo:rerun-if-env-changed=GS_STUDIO_EMBED_DATA");

    let mut files: Vec<(&str, String, PathBuf)> = Vec::new();
    if std::env::var_os("CARGO_FEATURE_BUNDLED_ART").is_some() {
        let pool = std::env::var_os("GS_STUDIO_EMBED_POOL").filter(|v| !v.is_empty()).map(PathBuf::from).unwrap_or_else(|| {
            panic!(
                "the bundled-art feature needs GS_STUDIO_EMBED_POOL: the pool whose art is packed \
                 (set it in .cargo/config.toml under [env], or in the environment)"
            )
        });
        let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
        let data = std::env::var_os("GS_STUDIO_EMBED_DATA")
            .filter(|v| !v.is_empty())
            .map(PathBuf::from)
            .unwrap_or_else(|| manifest.join("../../data"));
        for part in POOL_PARTS {
            collect(&pool, part, "pool", POOL_EXCLUDED, &mut files);
        }
        for part in DATA_PARTS {
            collect(&data, part, "data", &[], &mut files);
        }
        files.retain(|(root, rel, _)| *root != "data" || !rel.starts_with("textures/") || is_texture_file(rel));
        if !files.iter().any(|(root, _, _)| *root == "pool") {
            panic!("GS_STUDIO_EMBED_POOL={} holds no global/images, global/scenes or global/skins", pool.display());
        }
    }

    files.sort_by(|a, b| (a.0, &a.1).cmp(&(b.0, &b.1)));
    let mut blob = std::fs::File::create(out.join("bundle.bin")).expect("create bundle.bin");
    let mut index = String::from("/// (root, path relative to it with '/', offset, length) -- generated by build.rs.\n");
    index.push_str("pub static ENTRIES: &[(&str, &str, usize, usize)] = &[\n");
    let mut offset = 0usize;
    for (root, rel, path) in &files {
        println!("cargo:rerun-if-changed={}", path.display());
        let mut src = std::fs::File::open(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let len = std::io::copy(&mut src, &mut blob).unwrap_or_else(|e| panic!("{}: {e}", path.display())) as usize;
        writeln!(index, "    ({root:?}, {rel:?}, {offset}, {len}),").unwrap();
        offset += len;
    }
    index.push_str("];\n");
    std::fs::write(out.join("bundle_index.rs"), index).expect("write bundle_index.rs");
    if !files.is_empty() {
        println!("cargo:warning=bundled-art: packed {} files, {} MB", files.len(), offset / (1024 * 1024));
    }
}

/// Is `rel` (under `textures/`) one of the texture generator's files?
fn is_texture_file(rel: &str) -> bool {
    let name = rel.rsplit('/').next().unwrap_or(rel);
    TEXTURE_NAMES.contains(&name) || TEXTURE_ENDINGS.iter().any(|e| name.ends_with(e))
}

/// Every file under `base/part` (or `part` itself when it is a file), as
/// `(root, path relative to base with '/', absolute path)`, skipping the
/// `excluded` subtrees (relative to base) and backups.
fn collect(base: &Path, part: &str, root: &'static str, excluded: &[&str], out: &mut Vec<(&'static str, String, PathBuf)>) {
    let rel_of = |path: &Path| path.strip_prefix(base).unwrap_or(path).to_string_lossy().replace('\\', "/");
    let start = base.join(part);
    if start.is_file() {
        out.push((root, part.to_owned(), start));
        return;
    }
    let mut stack = vec![start];
    while let Some(dir) = stack.pop() {
        let Ok(entries) = std::fs::read_dir(&dir) else { continue };
        // Watch the directories too, so an added file triggers a repack.
        println!("cargo:rerun-if-changed={}", dir.display());
        for entry in entries.flatten() {
            let path = entry.path();
            if entry.file_name().to_string_lossy().ends_with(".bak") || excluded.contains(&rel_of(&path).as_str()) {
                continue;
            }
            match entry.file_type() {
                Ok(t) if t.is_dir() => stack.push(path),
                Ok(t) if t.is_file() => out.push((root, rel_of(&path), path)),
                _ => {}
            }
        }
    }
}
