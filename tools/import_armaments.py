# Ammunition names from the ranged file are arrowheads, not weapons.
SKIP = {"broadhead", "blunt", "bodkin point", "crescent", "Name"}

ENTRY = re.compile(
    r':category\s*=>\s*:(\w+),\s*:base_name\s*=>\s*"([^"]+)",\s*:all_names\s*=>\s*\[([^\]]*)\]'
)


def key(base):
    return re.sub(r"[^a-z0-9]+", "_", base.lower()).strip("_")


def toml_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    bases = {}
    files = sorted(LICH.glob("weapon_stats_*.rb")) + [LICH / "shield_stats.rb"]
    for f in files:
        for category, base, names in ENTRY.findall(f.read_text(encoding="utf-8")):
            if base in SKIP or category in ("natural",):
                continue
            entry = bases.setdefault(base, {"category": category, "names": set()})
            entry["names"].update(n for n in re.findall(r'"([^"]+)"', names))
    missing = sorted(b for b in bases if b not in SHAPES)
    if missing:
        sys.exit(f"no shape for: {', '.join(missing)} -- add them to SHAPES")

    text = OUT.read_text(encoding="utf-8")
    head = text.split(MARKER)[0].rstrip() + "\n\n" + MARKER + "\n"
    out = [head]
    drawn = 0
    for base in sorted(bases, key=str.lower):
        shape = SHAPES[base]
        if shape is None:
            continue
        drawn += 1
        name, length, hands = shape
        names = sorted(bases[base]["names"] | {base}, key=str.lower)
        out.append(
            f"\n[weapon.{key(base)}]\n"
            f"base = {toml_str(base)}\n"
            f"category = {toml_str(bases[base]['category'])}\n"
            f"shape = {toml_str(name)}\n"
            f"length = {length}\n"
            f"hands = {hands}\n"
            f"names = [{', '.join(toml_str(n) for n in names)}]\n"
        )
    OUT.write_text("".join(out), encoding="utf-8", newline="\n")
    print(f"{drawn} drawn bases of {len(bases)} written to {OUT}")


if __name__ == "__main__":
    main()
